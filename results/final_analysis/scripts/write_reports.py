PKG = os.path.dirname(HERE)


def T(name):
    return list(csv.DictReader(open(os.path.join(PKG, "TABLES", name + ".csv"), encoding="utf-8")))


def f(v, d=3):
    if v in ("", None, "nan"):
        return "—"
    return f"{float(v):.{d}f}"


def one(rows, **kw):
    for r in rows:
        if all(r.get(k) == v for k, v in kw.items()):
            return r
    raise KeyError(kw)


def ci(r, m, lo, hi, d=3):
    return f"{f(r[m], d)} [{f(r[lo], d)}, {f(r[hi], d)}]"


def LAB(c):
    return "headline (full length)" if c.startswith("semantic__sentence (full") else c.replace("__", " / ")


def n(v):
    return "—" if v in ("", None, "nan") else str(int(float(v)))


